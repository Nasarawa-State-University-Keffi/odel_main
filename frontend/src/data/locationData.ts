export const getStatesForCountry = (country: string): LocationOption[] => {
    if (country === "Nigeria") {
        return Object.keys(NIGERIA_STATES)
            .map(state => ({
                value: state,
                label: NIGERIA_STATES[state].name
            }))
            .sort((a, b) => a.label.localeCompare(b.label));
    }
    return [];
};

export const getLGAsForState = (country: string, state: string): LocationOption[] => {
    if (country === "Nigeria" && NIGERIA_STATES[state]) {
        return NIGERIA_STATES[state].lgas.map(lga => ({
            value: lga,
            label: lga
        }));
    }
    return [];
};
